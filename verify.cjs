const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({ Date });
vm.runInContext(fs.readFileSync('ritual.js', 'utf8') + '\nglobalThis.R = Ritual;', context);
const R = context.R;
const store = { days: {}, supplements: {} };
const day = '2026-11-20';
assert.equal(R.currentAction('morning', {}, undefined, store).id, 'brush');
R.saveAction(store, day, 'morning', 'brush', 'done');
assert.equal(R.currentAction('morning', R.getActions(store, day, 'morning'), undefined, store).id, 'stretch');
assert.equal(R.nextAction(store, 'morning', R.getActions(store, day, 'morning'), 'brush'), 'stretch');
R.saveAction(store, day, 'morning', 'stretch', 'skipped');
assert.equal(R.nextAction(store, 'morning', R.getActions(store, day, 'morning'), 'stretch'), 'read');
for (const step of R.getSteps(store, 'morning')) R.saveAction(store, day, 'morning', step.id, 'done');
assert.equal(R.currentAction('morning', R.getActions(store, day, 'morning'), undefined, store).id, 'finished');
assert.equal(R.currentAction('morning', R.getActions(store, day, 'morning'), 'brush', store).id, 'brush');
R.saveAction(store, day, 'morning', 'brush', undefined);
assert.equal(R.currentAction('morning', R.getActions(store, day, 'morning'), undefined, store).id, 'brush');
const custom = { id: 'custom-0123456789abcdef01234567', title: '练琴', label: '练琴' };
R.readEntry(store, 'habit-settings/morning', JSON.stringify([custom, { id: 'brush', title: '刷牙', paused: true }]));
assert.equal(R.getSteps(store, 'morning').length, 1);
assert.equal(R.getSteps(store, 'morning')[0].id, custom.id);
R.readEntry(store, `${day}/morning/${custom.id}`, JSON.stringify({ status: 'done', at: 1 }));
assert.equal(R.getActions(store, day, 'morning')[custom.id].status, 'done');
assert.equal(R.heatmap(store, 'morning', custom.id, day, 'week').filter(cell => cell.done).length, 1);
assert.equal(R.heatmap(store, 'evening', custom.id, day, 'week').filter(cell => cell.done).length, 0);
assert.equal(R.heatmap(store, 'morning', 'brush', '2024-02-15', 'month').length, 29);
assert.equal(R.heatmap(store, 'morning', 'brush', '2024-02-15', 'year').length, 366);
assert.equal(R.heatmap(store, 'morning', 'brush', day, 'year').length, 365);
assert.equal(R.heatmap(store, 'morning', 'brush', day, 'month').filter(cell => cell.future).length, 10);
assert.equal(R.activeDay('evening', new Date(2026, 0, 1, 2)), '2025-12-31');
R.setSupplementCheck(store, day, '0123456789abcdef01234567', 'morning');
assert.equal(R.heatmap(store, 'morning', 'supplement-0123456789abcdef01234567', day, 'week').filter(cell => cell.done).length, 1);
assert.equal(R.heatmap(store, 'evening', 'supplement-0123456789abcdef01234567', day, 'week').filter(cell => cell.done).length, 0);
const original = JSON.stringify(store.habits);
R.readEntry(store, 'habit-settings/morning', JSON.stringify([custom, custom]));
assert.equal(JSON.stringify(store.habits), original);
const configured = { habits: { morning: [custom, { id: 'read', label: '阅读' }, { id: 'brush', paused: true }] } };
const actions = { brush: { status: 'done', at: 50 }, read: { status: 'skipped', at: 20 }, [custom.id]: { status: 'skipped', at: 30 } };
const active = R.getSteps(configured, 'morning');
assert.equal(R.currentAction('morning', actions, undefined, configured).title, '今晨完成 0 项');
assert.equal(R.roundProgress(active, actions).latest, undefined);
actions[custom.id] = { status: 'done', at: 10 };
actions.read = { status: 'done', at: 5 };
assert.equal(R.roundProgress(active, actions).latest.id, custom.id);
delete actions[custom.id];
assert.equal(R.roundProgress(active, actions).latest.id, 'read');
assert.equal(R.currentAction('morning', {}, undefined, { habits: { morning: [] } }).title, '添加一个小习惯');
const journal = { days: {}, supplements: {}, habits: { morning: [{ ...custom, paused: true }] } };
const mark = (offset, period, id, status) => R.saveAction(journal, R.offsetDay(day, offset), period, id, status);
mark(0, 'morning', 'brush', 'skipped');
mark(-1, 'evening', 'supplement', 'done');
R.setSupplementCheck(journal, day, '0123456789abcdef01234567', 'morning');
R.saveNote(journal, day, 'snack', 'no');
mark(1, 'evening', 'walk', 'done');
assert.equal(R.companionGrowth(journal, day).days, 0);
for (let ago = 0; ago < 30; ago++) {
  mark(-ago, 'morning', custom.id, 'done');
  mark(-ago, 'evening', 'walk', 'done');
  const growth = R.companionGrowth(journal, day);
  assert.equal(growth.days, ago + 1);
  assert.equal(growth.stage, ago < 6 ? 'chick' : ago < 29 ? 'juvenile' : 'adult');
}
assert.equal(R.recentHabitDays(journal, 'morning', custom.id, day), 28);
assert.equal(R.recentHabitDays(journal, 'evening', custom.id, day), 0);
assert.equal(R.recentHabitDays(journal, 'morning', 'supplement-0123456789abcdef01234567', day), 1);
mark(0, 'morning', custom.id, undefined);
assert.equal(R.companionGrowth(journal, day).days, 30);
mark(0, 'evening', 'walk', undefined);
assert.equal(R.companionGrowth(journal, day).stage, 'juvenile');
assert.equal(R.recentHabitDays(journal, 'morning', custom.id, day), 27);
console.log('PASS: progression, skip, finish, undo, custom persistence, order, pause, historical counts, leap dates, midnight rollover, supplements, growth milestones and 28-day habit counts');
